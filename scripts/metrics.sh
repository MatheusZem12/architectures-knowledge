#!/usr/bin/env bash
# Actually measures each architecture and writes the result to RESULTS.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PORT="${VERIFY_PORT:-18080}"
BIN="$(mktemp -d)"
trap 'rm -rf "$BIN"' EXIT
OUT="$ROOT/RESULTS.md"

(cd "$ROOT/contract" && go build -o "$BIN/bench" ./cmd/bench)

count_lines() { # folder, find pattern; non-empty lines only
  find "$1" -name '*.go' "${@:2}" -print0 | xargs -0 -r cat | grep -cv '^[[:space:]]*$' || true
}

wait_health() {
  for _ in $(seq 1 100); do curl -fs "http://localhost:$PORT/health" >/dev/null 2>&1 && return 0; sleep 0.05; done
  echo "did not start" >&2; return 1
}

rss_kb() { # adds up the memory of the process and its direct children
  local total=0 pid
  for pid in "$1" $(pgrep -P "$1" || true); do
    if [ "$(cat "/proc/$pid/comm" 2>/dev/null)" != "run.sh" ]; then
      total=$((total + $(awk '/^VmRSS/{print $2}' "/proc/$pid/status" 2>/dev/null || echo 0)))
    fi
  done
  echo "$total"
}

{
  echo "# Measured results"
  echo
  echo "Generated by \`scripts/metrics.sh\` on $(date +%F), with $(go version | awk '{print $3}'), on $(nproc) cores."
  echo "Run it again to measure on your machine. Latency: $(grep -E '^\s+measured\s+=' "$ROOT/contract/cmd/bench/main.go" | awk '{print $3}') sequential orders, all on localhost."
  echo
  echo "| Architecture | .go files | Lines of code | Test lines | Packages | Largest file (lines) | Processes | Binaries (MB) | Memory after load (MB) | p50 POST /orders (µs) | p99 (µs) | Orders/s |"
  echo "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
} > "$OUT"

for dir in $(cd "$ROOT" && ls -d [0-9][0-9]-*/ | tr -d /); do
  cd "$ROOT/$dir"
  files=$(find . -name '*.go' | wc -l)
  code=$(count_lines . -not -name '*_test.go')
  tests=$(count_lines . -name '*_test.go')
  biggest=$(find . -name '*.go' -not -name '*_test.go' -exec wc -l {} + | grep -v ' total$' | sort -n | tail -1 | awk '{print $1}')

  if [ -x ./run.sh ]; then
    ./build.sh "$BIN/$dir"
    processes=6
    packages=$(cd services && for s in */; do (cd "$s" && go list ./... ); done | wc -l)
    BIN_DIR="$BIN/$dir" BASE_PORT="$PORT" ./run.sh >/dev/null 2>&1 &
    size=$(du -cb "$BIN/$dir"/* | tail -1 | cut -f1)
  else
    go build -o "$BIN/$dir" .
    processes=1
    packages=$(go list ./... | wc -l)
    PORT="$PORT" "$BIN/$dir" >/dev/null 2>&1 &
    size=$(stat -c %s "$BIN/$dir")
  fi
  pid=$!
  wait_health
  result=$(BASE_URL="http://localhost:$PORT" "$BIN/bench")
  memory=$(rss_kb "$pid")
  kill "$pid" 2>/dev/null || true
  wait "$pid" 2>/dev/null || true

  awk -v dir="$dir" -v files="$files" -v code="$code" -v tests="$tests" -v pkgs="$packages" -v big="$biggest" \
      -v procs="$processes" -v size="$size" -v mem="$memory" \
      -v p50="$(jq -r .p50_us <<<"$result")" -v p99="$(jq -r .p99_us <<<"$result")" -v rps="$(jq -r .rps <<<"$result")" \
      'BEGIN { printf "| %s | %d | %d | %d | %d | %d | %d | %.1f | %.1f | %d | %d | %d |\n", dir, files, code, tests, pkgs, big, procs, size/1048576, mem/1024, p50, p99, rps }' >> "$OUT"
  echo "measured: $dir"
done
